// Generate TypeScript API types from the committed OpenAPI document, locally and with an explicit configuration.
// Run by scripts/api_types.py from an installed copy of this project; not meant to be run directly.
//
//     node generate.mjs <openapi.json> <out.d.ts>
//
// The document is passed to openapi-typescript as parsed JSON, after refusing any non-local `$ref`, so nothing is
// read from a URL or another file. The Redocly configuration is this explicit object: no redocly.yaml discovery,
// no plugins, no registry tokens or resolver headers.
import { readFile, writeFile } from "node:fs/promises";
import { createConfig } from "@redocly/openapi-core";
import openapiTS, { astToString } from "openapi-typescript";

const BANNER = `// Generated by scripts/api_types.py from packages/policyops/openapi/v1.json with openapi-typescript 7.13.0.
// Do not edit; regenerate with \`python scripts/api_types.py --write\`.

`;

const args = process.argv.slice(2);
if (args.length !== 2) {
  console.error("usage: node generate.mjs <openapi.json> <out.d.ts>");
  process.exit(2);
}
const [input, output] = args;
const document = JSON.parse(await readFile(input, "utf8"));

const nonLocal = [];
const visit = (node) => {
  if (Array.isArray(node)) {
    node.forEach(visit);
  } else if (node !== null && typeof node === "object") {
    for (const [key, value] of Object.entries(node)) {
      if (key === "$ref" && !(typeof value === "string" && value.startsWith("#/"))) {
        nonLocal.push(String(value));
      }
      visit(value);
    }
  }
};
visit(document);
if (nonLocal.length > 0) {
  console.error(`refusing ${nonLocal.length} non-local $ref value(s)`);
  process.exit(1);
}

const redocly = await createConfig(
  { rules: { "operation-operationId-unique": { severity: "error" } } },
  { extends: ["minimal"] },
);
const ast = await openapiTS(document, { redocly, silent: true, cwd: new URL(".", import.meta.url) });
await writeFile(output, BANNER + astToString(ast).replaceAll("\r\n", "\n"), "utf8");
