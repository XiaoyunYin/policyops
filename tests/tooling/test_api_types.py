"""The API type generator driver's containment rules (offline; standard library only).

The generation itself (npm ci of the exactly locked generator plus the byte comparison) is the CI web job's
`scripts/api_types.py --check` step; these tests cover what must hold without a network.
"""

from __future__ import annotations

import importlib.util
import json
import os
from pathlib import Path
import tempfile
from types import ModuleType
import unittest
from unittest import mock


ROOT = Path(__file__).resolve().parents[2]


def load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("api_types_under_test", ROOT / "scripts" / "api_types.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class ApiTypesDriverTests(unittest.TestCase):
    def setUp(self) -> None:
        self.api_types = load()
        temp = tempfile.TemporaryDirectory(prefix="policyops-api-types-", dir=os.environ.get("POLICYOPS_TEMP_DIR"))
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        (self.root / "tmp").mkdir()

    def test_the_temporary_root_is_required_and_must_be_outside_the_repository(self) -> None:
        with mock.patch.dict(os.environ, {"POLICYOPS_TEMP_DIR": ""}), self.assertRaises(self.api_types.GenerationError):
            self.api_types.temp_root()
        for inside in (ROOT, ROOT / "apps" / "web"):
            with (mock.patch.dict(os.environ, {"POLICYOPS_TEMP_DIR": str(inside)}),
                  self.assertRaises(self.api_types.GenerationError)):
                self.api_types.temp_root()
        with mock.patch.dict(os.environ, {"POLICYOPS_TEMP_DIR": str(self.root)}):
            self.assertEqual(self.api_types.temp_root(), self.root.resolve())

    def test_cleanup_removes_only_its_own_run_directory(self) -> None:
        own = self.root / "tmp" / "api-types-0123abcd"
        (own / "node_modules").mkdir(parents=True)
        self.api_types.remove(own, self.root)
        self.assertFalse(own.exists())
        for other in (self.root / "tmp" / "other-run", self.root / "api-types-x", self.root / "tmp" / "a" /
                      "api-types-y", self.root / "tmp"):
            other.mkdir(parents=True, exist_ok=True)
            with self.assertRaises(self.api_types.GenerationError):
                self.api_types.remove(other, self.root)
            self.assertTrue(other.exists())

    def test_the_generator_project_is_exactly_pinned_and_script_free(self) -> None:
        project = ROOT / "scripts" / "api-types"
        manifest = json.loads((project / "package.json").read_text(encoding="utf-8"))
        self.assertEqual(manifest["devDependencies"], {"@redocly/openapi-core": "1.34.23",
                                                       "openapi-typescript": "7.13.0", "typescript": "5.9.3"})
        self.assertNotIn("dependencies", manifest)
        self.assertNotIn("scripts", manifest)
        lock = json.loads((project / "package-lock.json").read_text(encoding="utf-8"))
        packages = {name: entry for name, entry in lock["packages"].items() if name}
        self.assertEqual(lock["packages"]["node_modules/openapi-typescript"]["version"], "7.13.0")
        self.assertEqual(lock["packages"]["node_modules/typescript"]["version"], "5.9.3")
        for name, entry in packages.items():
            self.assertTrue(entry["resolved"].startswith("https://registry.npmjs.org/"), name)
            self.assertTrue(entry["integrity"].startswith("sha512-"), name)
        npmrc = (project / ".npmrc").read_text(encoding="utf-8").split()
        self.assertIn("ignore-scripts=true", npmrc)
        self.assertEqual(self.api_types.GENERATOR_FILES, ("package.json", "package-lock.json", ".npmrc",
                                                          "generate.mjs"))

    def test_the_generated_types_name_their_source(self) -> None:
        header = (ROOT / "apps" / "web" / "src" / "api" / "schema.d.ts").read_text(encoding="utf-8").splitlines()
        self.assertEqual(header[0], "// Generated by scripts/api_types.py from packages/policyops/openapi/v1.json "
                                    "with openapi-typescript 7.13.0.")


if __name__ == "__main__":
    unittest.main()
